using System.Diagnostics;
using LiteDB;
using LiteDbQuery = LiteDB.Query;
using LoahDB;
using Microsoft.Data.Sqlite;

namespace LoahDB.Benchmarks;

public static class QuickBenchmarkReport
{
    private const int DocumentCount = 10_000;

    public static void WriteReport(string outputPath)
    {
        var baseDir = Path.Combine(Path.GetTempPath(), "LoahDB.QuickReport", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(baseDir);
        try
        {
            var seed = Enumerable.Range(0, DocumentCount)
                .Select(i => new BenchmarkDocument
                {
                    Id = i.ToString("D8"),
                    Name = $"User{i}",
                    Email = $"user{i}@example.com",
                    Age = 20 + (i % 50),
                    Score = i * 3,
                })
                .ToList();

            var loahOptions = new LoahOptions
            {
                BasePath = baseDir,
                StorageFormat = LoahStorageFormat.PageFile,
            };
            var sqlitePath = Path.Combine(baseDir, "bench.sqlite");
            var liteDbPath = Path.Combine(baseDir, "bench.litedb");

            var loahInsert = Time(() =>
            {
                var root = "loah-insert-" + Guid.NewGuid().ToString("N");
                using var store = new LoahStore(root, loahOptions);
                var col = store.Collection<BenchmarkDocument>("docs");
                col.EnsureIndex("by_email", d => d.Email);
                col.InsertMany(seed);
            });

            var loahLookup = Time(() =>
            {
                using var store = new LoahStore("loah", loahOptions);
                var col = store.Collection<BenchmarkDocument>("docs");
                _ = col.GetById(seed[DocumentCount / 2].Id);
            });

            var loahRange = Time(() =>
            {
                using var store = new LoahStore("loah", loahOptions);
                var col = store.Collection<BenchmarkDocument>("docs");
                _ = col.Query().Where(d => d.Age >= 40 && d.Age <= 45).Count();
            });

            var loahDelete = Time(() =>
            {
                using var store = new LoahStore("loah", loahOptions);
                store.Collection<BenchmarkDocument>("docs").Delete(seed[^1].Id);
            });

            SqliteSeed(sqlitePath, seed);
            var sqliteLookup = Time(() => SqliteScalar(sqlitePath, "SELECT email FROM docs WHERE id = $id",
                ("$id", seed[DocumentCount / 2].Id)));
            var sqliteRange = Time(() => SqliteScalar(sqlitePath,
                "SELECT COUNT(*) FROM docs WHERE age >= 40 AND age <= 45"));
            var sqliteDelete = Time(() =>
            {
                using var connection = new SqliteConnection($"Data Source={sqlitePath}");
                connection.Open();
                using var cmd = connection.CreateCommand();
                cmd.CommandText = "DELETE FROM docs WHERE id = $id";
                cmd.Parameters.AddWithValue("$id", seed[^1].Id);
                cmd.ExecuteNonQuery();
            });

            LiteSeed(liteDbPath, seed);
            var liteLookup = Time(() =>
            {
                using var db = new LiteDatabase(liteDbPath);
                _ = db.GetCollection<BenchmarkDocument>("docs")
                    .FindById(seed[DocumentCount / 2].Id);
            });
            var liteRange = Time(() =>
            {
                using var db = new LiteDatabase(liteDbPath);
                _ = db.GetCollection<BenchmarkDocument>("docs")
                    .Count(LiteDbQuery.And(LiteDbQuery.GTE("Age", 40), LiteDbQuery.LTE("Age", 45)));
            });
            var liteDelete = Time(() =>
            {
                using var db = new LiteDatabase(liteDbPath);
                db.GetCollection<BenchmarkDocument>("docs").Delete(seed[^1].Id);
            });

            var sqliteInsert = Time(() =>
                SqliteSeed(Path.Combine(baseDir, "bench-insert-" + Guid.NewGuid().ToString("N") + ".sqlite"), seed));
            var liteInsert = Time(() =>
                LiteSeed(Path.Combine(baseDir, "bench-insert-" + Guid.NewGuid().ToString("N") + ".litedb"), seed));

            var markdown =
                $"""
                # LoahDB benchmark report (quick)

                Generated by `LoahDB.Benchmarks --quick-report`. Document count: **{DocumentCount:N0}**.
                LoahDB uses **page-file** storage (`LoahStorageFormat.PageFile`). Times are wall-clock milliseconds (median of 3 runs).

                | Scenario | LoahDB | SQLite | LiteDB |
                |----------|--------|--------|--------|
                | Bulk insert | {loahInsert:F1} | {sqliteInsert:F1} | {liteInsert:F1} |
                | Point lookup | {loahLookup:F1} | {sqliteLookup:F1} | {liteLookup:F1} |
                | Range / filter count | {loahRange:F1} | {sqliteRange:F1} | {liteRange:F1} |
                | Delete by id | {loahDelete:F1} | {sqliteDelete:F1} | {liteDelete:F1} |

                For full BenchmarkDotNet results (including 100k rows), run:

                ```bash
                dotnet run -c Release --project LoahDB.Benchmarks
                ```
                """;

            var directory = Path.GetDirectoryName(outputPath);
            if (!string.IsNullOrEmpty(directory))
            {
                Directory.CreateDirectory(directory);
            }

            File.WriteAllText(outputPath, markdown);
            Console.WriteLine($"Wrote {outputPath}");
        }
        finally
        {
            if (Directory.Exists(baseDir))
            {
                Directory.Delete(baseDir, recursive: true);
            }
        }
    }

    private static double Time(Action action)
    {
        var samples = new List<double>();
        for (var i = 0; i < 3; i++)
        {
            var sw = Stopwatch.StartNew();
            action();
            sw.Stop();
            samples.Add(sw.Elapsed.TotalMilliseconds);
        }

        samples.Sort();
        return samples[samples.Count / 2];
    }

    private static void SqliteSeed(string path, List<BenchmarkDocument> seed)
    {
        if (File.Exists(path))
        {
            File.Delete(path);
        }

        using var connection = new SqliteConnection($"Data Source={path}");
        connection.Open();
        using var cmd = connection.CreateCommand();
        cmd.CommandText =
            """
            CREATE TABLE docs (
              id TEXT PRIMARY KEY,
              name TEXT NOT NULL,
              email TEXT NOT NULL,
              age INTEGER NOT NULL,
              score INTEGER NOT NULL);
            """;
        cmd.ExecuteNonQuery();
        using var tx = connection.BeginTransaction();
        foreach (var doc in seed)
        {
            using var insert = connection.CreateCommand();
            insert.Transaction = tx;
            insert.CommandText = "INSERT INTO docs VALUES ($id,$name,$email,$age,$score)";
            insert.Parameters.AddWithValue("$id", doc.Id);
            insert.Parameters.AddWithValue("$name", doc.Name);
            insert.Parameters.AddWithValue("$email", doc.Email);
            insert.Parameters.AddWithValue("$age", doc.Age);
            insert.Parameters.AddWithValue("$score", doc.Score);
            insert.ExecuteNonQuery();
        }

        tx.Commit();
    }

    private static double SqliteScalar(string path, string sql, params (string name, object value)[] parameters)
    {
        return Time(() =>
        {
            using var connection = new SqliteConnection($"Data Source={path}");
            connection.Open();
            using var cmd = connection.CreateCommand();
            cmd.CommandText = sql;
            foreach (var (name, value) in parameters)
            {
                cmd.Parameters.AddWithValue(name, value);
            }

            cmd.ExecuteScalar();
        });
    }

    private static void LiteSeed(string path, List<BenchmarkDocument> seed)
    {
        if (File.Exists(path))
        {
            File.Delete(path);
        }

        using var db = new LiteDatabase(path);
        var col = db.GetCollection<BenchmarkDocument>("docs");
        col.InsertBulk(seed);
    }
}
